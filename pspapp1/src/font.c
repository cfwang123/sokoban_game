static int glyph_index(char c)
{
    if (c >= 'a' && c <= 'z')
        c = (char)(c - 'a' + 'A');
    if (c < 32 || c > 90)
        return 0;
    return c - 32;
}

void font_draw_char(float x, float y, float scale, char c, uint32_t color)
{
    const unsigned char *g = glyphs[glyph_index(c)];
    int row, col;
    float px = scale;

    for (row = 0; row < 7; row++) {
        unsigned char bits = g[row];
        for (col = 0; col < 5; col++) {
            if (bits & (0x10 >> col)) {
                gfx_rect(x + col * px, y + row * px, px, px, color);
            }
        }
    }
}

void font_draw(float x, float y, float scale, const char *text, uint32_t color)
{
    float cx = x;
    float advance = 6.0f * scale;
    while (*text) {
        if (*text == '\n') {
            y += 8.0f * scale;
            cx = x;
        } else {
            font_draw_char(cx, y, scale, *text, color);
            cx += advance;
        }
        text++;
    }
}

float font_width(const char *text, float scale)
{
    int n = 0;
    while (text[n] && text[n] != '\n')
        n++;
    if (n <= 0)
        return 0.0f;
    return n * 6.0f * scale;
}

void font_draw_centered(float cx, float y, float scale, const char *text, uint32_t color)
{
    float w = font_width(text, scale);
    font_draw(cx - w * 0.5f, y, scale, text, color);
}
